    with closing(db()) as conn:
        conn.execute("BEGIN IMMEDIATE")
        stock = conn.execute("SELECT current_price FROM stocks WHERE id=?", (stock_id,)).fetchone()
        if not stock: conn.rollback(); raise HTTPException(404, "Акция не найдена")
